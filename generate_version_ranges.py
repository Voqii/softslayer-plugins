version_hashes = sorted(version_hashes.items(), key=lambda item: version_sorter(item[0]))

ranges = [[]]
current_hash = None
for version, hash in version_hashes:
    if current_hash is None:
        current_hash = hash

    elif current_hash != hash:
        # Reset
        current_hash = hash
        ranges.append([])

    ranges[-1].append(version)

print(ranges)

with open(f"buildSrc/src/main/kotlin/{platform_capitalized}VersionRanges.kt", "w") as f:
    f.write("// GENERATED BY generate_version_ranges.py - DO NOT EDIT BY HAND\n")
    f.write("// Make sure to update the GitHub Actions workflow if this changes\n")
    f.write(f"val {platform}VersionRanges = mapOf(\n")
    for range in ranges:
        f.write(f"    \"{range[0]}\" to listOf(")
        f.write(", ".join(map(lambda v: f"\"{v}\"", range)))
        f.write("),\n")
    f.write(")\n")
